/// Shared spacing scale for layout and component padding.
class AppSpacing {
  AppSpacing._();

  static const double xs = 4.0;
  static const double sm = 8.0;
  static const double md = 12.0;
  static const double lg = 16.0;
  static const double xl = 20.0;
  static const double xxl = 24.0;
  static const double xxxl = 32.0;

  static const double section = 40.0;
  static const double sectionLarge = 48.0;
  static const double sectionXLarge = 64.0;

  static const double screenHorizontal = xl;
  static const double screenVertical = xxl;
  static const double cardPadding = lg;
  static const double inputPadding = lg;
  static const double buttonPadding = lg;

  // Named gaps are retained for readability at call sites.
  static const double gapXs = xs;
  static const double gapSm = sm;
  static const double gapMd = md;
  static const double gapLg = lg;
  static const double gapXl = xxl;
  static const double gapXxl = xxxl;
}
